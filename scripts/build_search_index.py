"""Rebuild the browser search index after editing HTML; no dependencies required."""
import json
import re
import unicodedata
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

class Element:
    def __init__(self, tag='', attrs=None):
        self.tag = tag
        self.attrs = attrs or {}
        self.children = []

    def text(self):
        return ' '.join(' '.join(child.text() if isinstance(child, Element) else child for child in self.children).split())

    def find(self, predicate):
        found = [self] if predicate(self) else []
        for child in self.children:
            if isinstance(child, Element):
                found.extend(child.find(predicate))
        return found

class Document(HTMLParser):
    def __init__(self, content):
        super().__init__()
        self.root = Element()
        self.stack = [self.root]
        self.feed(content)

    def handle_starttag(self, tag, attrs):
        node = Element(tag, dict(attrs))
        self.stack[-1].children.append(node)
        if tag not in {'area','base','br','col','embed','hr','img','input','link','meta','param','source','track','wbr'}:
            self.stack.append(node)

    def handle_endtag(self, tag):
        for i in range(len(self.stack)-1, 0, -1):
            if self.stack[i].tag == tag:
                self.stack = self.stack[:i]
                break

    def handle_data(self, data):
        self.stack[-1].children.append(data)

entries = []
for relative, title in [('index.html','Home'), ('about-2/index.html','About Paul Simeon'), ('research/index.html','Research'), ('publications/index.html','Publications'), ('teaching/index.html','Teaching')]:
    path = ROOT / relative
    content = path.read_text()
    doc = Document(content).root
    main = doc.find(lambda n: n.tag == 'main')[0]
    description = doc.find(lambda n: n.tag == 'meta' and n.attrs.get('name') == 'description')[0].attrs['content']
    entries.append(dict(title=title, kind='Page', url=relative, text=description, keywords=main.text()))
    for node in main.find(lambda n: n.tag == 'article' and 'data-publication' in n.attrs):
        heading = node.find(lambda n: n.tag == 'h2')[0].text()
        slug = re.sub(r'[^a-z0-9]+', '-', unicodedata.normalize('NFKD', heading).encode('ascii','ignore').decode().lower()).strip('-')
        anchor = node.attrs.get('id', 'paper-' + slug)
        if 'id' not in node.attrs:
            content = content.replace('<article class="publication" data-publication>', '<article class="publication" data-publication id="'+anchor+'">', 1)
        entries.append(dict(title=heading, kind='Publication', url=relative+'#'+anchor, text=node.text()))
    for node in main.find(lambda n: n.tag == 'section' and n.attrs.get('id') in {'cosmic-rays','shocks','connections','other-interests'}):
        heading = node.find(lambda n: n.tag == 'h2')[0].text()
        entries.append(dict(title=heading, kind='Research', url=relative+'#'+node.attrs['id'], text=node.text()))
    if relative == 'about-2/index.html':
        entries.append(dict(title='Get in touch', kind='Contact', url=relative+'#contact', text='Contact Paul Simeon by email, LinkedIn, or X / Twitter. paulsimeon@gmail.com'))
    if content != path.read_text():
        path.write_text(content)

(ROOT/'assets/search-index.js').write_text('// Generated by scripts/build_search_index.py; do not edit directly.\nwindow.SITE_SEARCH_INDEX = '+json.dumps(entries, ensure_ascii=False, indent=2)+';\n')
print(f'Indexed {len(entries)} pages, sections, and publications.')
